/** the bibliography id a shelf book cites — its own imprint */
const bibId = (b: ShelfBook) => `${b.id}-imprint`;

/**
 * Each book becomes an entity of type `work`, shelved in its wing and dated so
 * the wing's floor timeline puts it in the right decade. The single claim is
 * the one thing a printed book documents beyond argument — that it was
 * published, by whom, and when — cited to its own imprint.
 */
export const shelfBookEntities: Entity[] = SHELF_BOOKS.map((b) => ({
  id: b.id,
  type: 'work' as const,
  name: b.title,
  epithet: b.epithet,
  dates: b.dates,
  year: b.year,
  era: b.era,
  cluster: b.cluster,
  summary: b.summary,
  claims: [
    {
      text: `${b.author}, ${b.title} (${b.dates}). ${b.imprint}.`,
      evidence: 'documented' as const,
      sources: [bibId(b)],
    },
  ],
  relations: [b.link, ...(b.also ?? [])],
  tags: [...b.tags, 'shelf'],
}));

export const shelfBookSources: Source[] = SHELF_BOOKS.map((b) => ({
  id: bibId(b),
  kind: 'primary' as const,
  title: b.title,
  author: b.author,
  year: b.dates,
  citation: `${b.author}, ${b.title}, ${b.imprint}, ${b.dates}.`,
}));

/** onward doors, merged into EXTERNAL_LINKS at the curated layer's strength */
export const shelfBookLinks: Record<string, string> = Object.fromEntries(
  SHELF_BOOKS.filter((b) => b.wiki).map((b) => [b.id, b.wiki as string]),
);
