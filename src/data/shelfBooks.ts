/**
 * THE SHELVES' REAL BOOKS.
 *
 * The wings were short of the one thing a library is made of. Each hall held
 * roughly fifty entries and only eight to fifteen of them were actually BOOKS;
 * the rest were people, cities, symbols and ideas, and every one of those
 * offers the visitor a Wikipedia article. Walk a corridor and you are mostly
 * being handed encyclopaedia entries by a building that looks like a library.
 *
 * This file is the correction: dozens of real, named, published titles per
 * wing, each shelved in the hall whose tradition it belongs to and dated so it
 * lands at the right point on that wing's brass floor timeline.
 *
 * ── why the records are compressed ────────────────────────────────────────
 *
 * A full `Entity` runs about twenty lines, and every claim it makes has to
 * cite the bibliography, so two hundred books written out longhand would be
 * four thousand lines of entity plus fifteen hundred of `Source` — and the two
 * would drift apart the first time a year was corrected in one and not the
 * other. So a book is declared ONCE, as a `ShelfBook`, and the entity, its
 * citation and its onward link are all derived from that single record below.
 * A title's imprint is its own documentation, which is exactly the claim each
 * derived entity makes and exactly what the derived `Source` records.
 *
 * ── what belongs here ─────────────────────────────────────────────────────
 *
 * Real titles only, by real authors, with real years of publication — the
 * books these traditions were actually built out of and argued over, including
 * the partisan ones. `wiki` is filled in only where I am confident the article
 * exists; where a title has no article of its own it points at its AUTHOR's,
 * which is a real door rather than a guessed one. No archive.org identifiers
 * are invented here: `archiveTexts.ts` holds those, and every id in it was
 * checked against the metadata API. A book with no verified scan simply links
 * to Wikipedia, and says so.
 */
export interface ShelfBook {
  /** entity id — also the bibliography id, prefixed `bk-` */
  id: string;
  title: string;
  author: string;
  /** display dates for the label, e.g. "1801" or "1875–77" */
  dates: string;
  /** representative year, for the wing's chronological ordering */
  year: number;
  era: EraId;
  cluster: ClusterId;
  /** the one-line label under the spine */
  epithet: string;
  /** what it is and why it is on this shelf */
  summary: string;
  /** the entity this book hangs off — an author, a subject, an order */
  link: { kind: RelationKind; target: string };
  /** further threads into the collection */
  also?: { kind: RelationKind; target: string }[];
  tags: string[];
  /** Wikipedia article title, underscored. The book's own where one exists,
   *  otherwise its author's. Omitted rather than guessed. */
  wiki?: string;
  /** publisher and place, for the citation */
  imprint: string;
}

